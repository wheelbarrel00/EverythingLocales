-- Korean (koKR) translations for the Everything Quests addon family.
--
-- HOW TO USE: type the Korean translation between the quotes after each "=".
-- The English text is the key inside L["..."]. Example:
--     L["Hide tracker in combat"] = "..."
--
-- This is the single source of Korean for EVERY addon in the family. Which addon
-- a phrase belongs to is decided when the locale files are built, so a phrase that
-- moves from one addon to another keeps its translation with no work from anyone.
-- store/_phrases.lua lists every phrase in use and which addon uses it.
--
-- KEEP THESE EXACTLY AS THEY APPEAR (do not translate them):
--   |cffaaaaaa ... |r   -> color codes
--   %d  %s              -> numbers / names get inserted here
--   %1$s  %2$d          -> the same, when the order has to change in Korean
--   \n                  -> line break
--   \"                  -> an escaped quote inside the text
--
-- A phrase left out of this file simply renders in English, so a partial
-- translation is always safe. Sorted by English key.

